package edu.pes.exam.exam;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;
import java.math.BigDecimal;
import java.sql.Timestamp;
import java.time.Instant;
import java.util.Map;
import java.util.UUID;

import com.fasterxml.jackson.databind.ObjectMapper;
import edu.pes.exam.security.PortalPrincipal;
import jakarta.validation.Validation;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.web.server.ResponseStatusException;

class ExamControllerTest {
    private JdbcTemplate jdbc;
    private ExamController controller;
    private final UUID teacherId = UUID.randomUUID();
    private final PortalPrincipal teacher = new PortalPrincipal(teacherId, "teacher@example.test", "TEACHER");
    private final Instant startsAt = Instant.parse("2026-12-01T09:00:00Z");

    @BeforeEach
    void setUpDatabase() {
        JdbcDataSource dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:exam-create-" + UUID.randomUUID() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1");
        jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("CREATE TABLE exams (id UUID PRIMARY KEY, created_by UUID NOT NULL, title VARCHAR(200) NOT NULL, subject VARCHAR(160) NOT NULL, duration_minutes INTEGER NOT NULL, starts_at TIMESTAMP NOT NULL, ends_at TIMESTAMP NOT NULL, total_marks NUMERIC(10,2) NOT NULL, passing_marks NUMERIC(10,2) NOT NULL, negative_mark_percent INTEGER NOT NULL, show_answers_after_submit BOOLEAN NOT NULL, max_attempts INTEGER NOT NULL, randomize_questions BOOLEAN NOT NULL, randomize_options BOOLEAN NOT NULL, status VARCHAR(20) NOT NULL)");
        jdbc.execute("CREATE TABLE audit_log (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor_id UUID NOT NULL, action VARCHAR(100) NOT NULL, entity_type VARCHAR(80) NOT NULL, entity_id VARCHAR(100) NOT NULL)");
        controller = new ExamController(jdbc, new ObjectMapper(), new ExamScoringService());
    }

    @Test
    void createsDraftAndPersistsAllIssueSevenFields() {
        var request = request("Algebra final", "Mathematics", 45, startsAt, startsAt.plusSeconds(7200),
                new BigDecimal("40"), new BigDecimal("24"));

        Map<String, Object> response = controller.createExam(request, teacher);

        assertEquals("DRAFT", response.get("status"));
        assertTrue(response.get("id") instanceof UUID);
        Map<String, Object> persisted = jdbc.queryForMap("SELECT * FROM exams WHERE id=?", response.get("id"));
        assertEquals(teacherId, persisted.get("created_by"));
        assertEquals("Algebra final", persisted.get("title"));
        assertEquals("Mathematics", persisted.get("subject"));
        assertEquals(45, persisted.get("duration_minutes"));
        assertEquals(Timestamp.from(startsAt), persisted.get("starts_at"));
        assertEquals(Timestamp.from(startsAt.plusSeconds(7200)), persisted.get("ends_at"));
        assertEquals(new BigDecimal("40.00"), persisted.get("total_marks"));
        assertEquals(new BigDecimal("24.00"), persisted.get("passing_marks"));
        assertEquals("DRAFT", persisted.get("status"));
        assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM audit_log WHERE entity_id=?", Integer.class, response.get("id").toString()));
        assertEquals("EXAM_CREATE", jdbc.queryForObject("SELECT action FROM audit_log WHERE entity_id=?", String.class, response.get("id").toString()));
    }

    @Test
    void rejectsInvalidTimeWindowBeforeWriting() {
        var request = request("Algebra final", "Mathematics", 45, startsAt, startsAt,
                new BigDecimal("40"), new BigDecimal("24"));

        ResponseStatusException error = assertThrows(ResponseStatusException.class,
                () -> controller.createExam(request, teacher));

        assertEquals("The exam end must be after the start.", error.getReason());
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM exams", Integer.class));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM audit_log", Integer.class));
    }

    @Test
    void rejectsPassingMarksAboveTotalBeforeWriting() {
        var request = request("Algebra final", "Mathematics", 45, startsAt, startsAt.plusSeconds(7200),
                new BigDecimal("20"), new BigDecimal("24"));

        ResponseStatusException error = assertThrows(ResponseStatusException.class,
                () -> controller.createExam(request, teacher));

        assertEquals("Passing marks cannot exceed total marks.", error.getReason());
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM exams", Integer.class));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM audit_log", Integer.class));
    }

    @Test
    void validatesTitleSubjectAndDurationRequestConstraints() {
        try (var factory = Validation.buildDefaultValidatorFactory()) {
            var invalid = request(" ", " ", 4, startsAt, startsAt.plusSeconds(7200),
                    BigDecimal.TEN, BigDecimal.ONE);

            var violations = factory.getValidator().validate(invalid);

            assertTrue(violations.stream().anyMatch(v -> v.getPropertyPath().toString().equals("title")));
            assertTrue(violations.stream().anyMatch(v -> v.getPropertyPath().toString().equals("subject")));
            assertTrue(violations.stream().anyMatch(v -> v.getPropertyPath().toString().equals("durationMinutes")));
        }
    }

    @Test
    void answerRequestPreservesAnswersAndReviewFlag() {
        var answer = new ExamController.AnswerRequest(java.util.List.of("Option B"), true);

        assertEquals(java.util.List.of("Option B"), answer.answers());
        assertTrue(answer.markedForReview());
    }

    private ExamController.ExamRequest request(String title, String subject, int duration, Instant start, Instant end,
                                              BigDecimal total, BigDecimal passing) {
        return new ExamController.ExamRequest(title, subject, duration, start, end, total, passing,
                0, false, 1, false, false);
    }
}
